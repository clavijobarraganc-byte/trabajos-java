    // Botón ELIMINAR REGISTRO
    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un empleado de la tabla para eliminar.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(
            this,
            "¿Desea eliminar la fila seleccionada?",
            "Confirmar",
            JOptionPane.YES_NO_OPTION
        );

        if (confirmar == JOptionPane.YES_OPTION) {
            if (fila < lista.size()) {
                lista.remove(fila);
            }
            modelo.removeRow(fila);
            actualizarEstadisticas();
            JOptionPane.showMessageDialog(this, "Registro eliminado exitosamente.", "Eliminado", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

