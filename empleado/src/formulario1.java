    // Botón GUARDAR
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = txtnombre.getText().trim();
        String documento = txtdocumento.getText().trim();
        String cargo = cbmCargo.getSelectedItem() != null ? cbmCargo.getSelectedItem().toString() : "";
        String area = cbmArea.getSelectedItem() != null ? cbmArea.getSelectedItem().toString() : "";
        Object salarioObj = spnSalario.getValue();
        String fecha = txtingreso.getText().trim();

        // 1. Validar que no haya campos vacíos
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor ingrese el Nombre Completo.", "Falta Información", JOptionPane.WARNING_MESSAGE);
            txtnombre.requestFocus();
            return;
        }

        if (documento.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor ingrese el Documento.", "Falta Información", JOptionPane.WARNING_MESSAGE);
            txtdocumento.requestFocus();
            return;
        }

        if (cargo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un Cargo.", "Falta Información", JOptionPane.WARNING_MESSAGE);
            cbmCargo.requestFocus();
            return;
        }

        if (area.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un Área.", "Falta Información", JOptionPane.WARNING_MESSAGE);
            cbmArea.requestFocus();
            return;
        }

        // 2. Validar que el salario sea mayor a 0 (Nivel Intermedio)
        double salario = 0;
        try {
            if (salarioObj instanceof Number) {
                salario = ((Number) salarioObj).doubleValue();
            } else {
                salario = Double.parseDouble(salarioObj.toString().trim());
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Salario no válido.", "Error", JOptionPane.ERROR_MESSAGE);
            spnSalario.requestFocus();
            return;
        }

        if (salario <= 0) {
            JOptionPane.showMessageDialog(this, "El salario debe ser mayor a 0.", "Salario Inválido", JOptionPane.WARNING_MESSAGE);
            spnSalario.requestFocus();
            return;
        }

        if (fecha.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor ingrese la Fecha de Ingreso.", "Falta Información", JOptionPane.WARNING_MESSAGE);
            txtingreso.requestFocus();
            return;
        }

        // 3. Crear el objeto empleado y agregar a la lista y a la tabla
        empleados nuevo = new empleados(nombre, documento, cargo, area, salario, fecha);
        lista.add(nuevo);

        modelo.addRow(new Object[] {
            nuevo.getNombre(),
            nuevo.getDocumento(),
            nuevo.getCargo(),
            nuevo.getArea(),
            String.format("$%,.2f", nuevo.getSalario())
        });

        // 4. Actualizar estadísticas (Nivel Avanzado)
        actualizarEstadisticas();

        JOptionPane.showMessageDialog(this, "Empleado registrado con éxito.", "Registro", JOptionPane.INFORMATION_MESSAGE);

        // Limpiar controles
        limpiar();
    }//GEN-LAST:event_jButton1ActionPerformed

