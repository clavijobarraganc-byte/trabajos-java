    /**
     * Nivel Avanzado: Calcula total, promedio y mayor salario
     */
    private void actualizarEstadisticas() {
        int total = lista.size();
        lblTotal.setText("Cantidad de empleados: " + total);

        if (total == 0) {
            lblPromedio.setText("Promedio salarial: $0.00");
            lblMayor.setText("Empleado con mayor salario: Ninguno");
            return;
        }

        double suma = 0;
        empleados mayor = lista.get(0);

        for (empleados e : lista) {
            suma += e.getSalario();
            if (e.getSalario() > mayor.getSalario()) {
                mayor = e;
            }
        }

        double promedio = suma / total;
        lblPromedio.setText(String.format("Promedio salarial: $%,.2f", promedio));
        lblMayor.setText(String.format("Empleado con mayor salario: %s ($%,.2f)", mayor.getNombre(), mayor.getSalario()));
    }

